"""Generate frontend/src/lib/api-types.ts from the FastAPI / Pydantic schemas.

The frontend never hand-writes API shapes: this file is regenerated whenever a response model
changes, and tests/test_contract_types.py fails if the committed file is out of date.

Usage:  python scripts/generate_ts_types.py
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import sys
import typing
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("VALUENGINE_WARMUP", "0")
OUTPUT = ROOT / "frontend" / "src" / "lib" / "api-types.ts"
UNION_ALIASES = ("IntrinsicResult", "SensitivityResult", "ExpectationsResult")
SKIP = {"HTTPValidationError", "ValidationError"}


def identifier(name: str) -> str:
    return re.sub(r"[^0-9A-Za-z_]", "_", name)


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return identifier(schema["$ref"].split("/")[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(ts_type(s) for s in schema[key]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate() -> str:
    from backend.main import app
    from backend.schemas import responses

    schemas = app.openapi()["components"]["schemas"]
    status = " | ".join(json.dumps(v) for v in typing.get_args(responses.Status))
    lines = [
        "// Generated by scripts/generate_ts_types.py from the API's Pydantic models. Do not edit by hand.",
        "/* eslint-disable */",
        "",
        f"export type Status = {status}",
        "",
        "export interface Envelope<T> {",
        "  status: Status",
        "  data: T | null",
        "  warnings: string[]",
        "  errors: string[]",
        "  provenance: Provenance | null",
        "}",
        "",
    ]
    for name in sorted(schemas):
        if name.startswith("Envelope_") or name in SKIP:
            continue
        schema = schemas[name]
        if "properties" not in schema:
            lines += [f"export type {identifier(name)} = {ts_type(schema)}", ""]
            continue
        required = set(schema.get("required", []))
        lines.append(f"export interface {identifier(name)} {{")
        for prop, prop_schema in schema["properties"].items():
            optional = "" if prop in required else "?"
            lines.append(f"  {prop}{optional}: {ts_type(prop_schema)}")
        lines += ["}", ""]
    for alias in UNION_ALIASES:
        union = typing.get_args(getattr(responses, alias))[0]
        members = " | ".join(member.__name__ for member in typing.get_args(union))
        lines.append(f"export type {alias} = {members}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
